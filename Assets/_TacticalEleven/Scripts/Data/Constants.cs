    /// <summary>
    /// Códigos que no son ISO3 (FIFA o legado) y su equivalente ISO3, que es el
    /// nombre de archivo de las banderas en `Resources/Flags`.
    /// </summary>
    public static readonly Dictionary<string, string> FlagAliases = new()
