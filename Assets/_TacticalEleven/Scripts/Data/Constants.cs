        { "ALG", "DZA" }, { "BUL", "BGR" }, { "CHI", "CHL" }, { "CRC", "CRI" },
        { "CRO", "HRV" }, { "CTA", "CAF" }, { "DEN", "DNK" }, { "ENG", "GBR" },
